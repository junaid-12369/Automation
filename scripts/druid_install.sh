# MAIN
#----------------------------------------------------------------
main() {
    log "INFO" "=== Druid ${DRUID_VERSION} automated installation started ==="
    detect_os
    install_prereqs

    load_state
    if [ "$STATE_EXISTS" == "no" ]; then
        prompt_volume
        prompt_druid_config
    else
        log "INFO" "Re-using saved volume '$VOLUME_NAME' -> $BASE_PATH and saved metadata/storage/credential settings (not re-prompting)."
    fi

    build_required_extensions
    setup_paths
    create_service_user

    NEED_INSTALL="yes"
    if [ "$STATE_EXISTS" == "yes" ] \
        && [ "${INSTALLED_DRUID_VERSION:-}" == "$DRUID_VERSION" ] \
        && [ -x "${DRUID_BINARIES}/bin/start-micro-quickstart" ]; then
        NEED_INSTALL="no"
        log "INFO" "Druid ${DRUID_VERSION} is already installed at $DRUID_BINARIES - skipping download/extract/reconfigure. Use --reconfigure to force a fresh install, or bump DRUID_VERSION to upgrade."
    fi

    if [ "$NEED_INSTALL" == "yes" ]; then
        download_and_install_druid
        prune_extensions
        write_configs
    fi

    create_systemd_service
    open_firewall_ports
    persist_state
    start_and_verify

    log "INFO" "=== Druid installation completed successfully ==="
    echo ""
    echo "Access log: $ACCESS_LOG"
    echo "Error log : $ERROR_LOG"
}

main "$@"

