#----------------------------------------------------------------
# 9. SYSTEMD SERVICE
#----------------------------------------------------------------
create_systemd_service() {
    local DRUID_SERVICE_FILE="/etc/systemd/system/druid.service"

    log "INFO" "Creating systemd unit at $DRUID_SERVICE_FILE"
    cat > "$DRUID_SERVICE_FILE" <<EOF
[Unit]
Description=Apache Druid server (micro-quickstart)
After=network.target multi-user.target

[Service]
Type=simple
User=${DRUID_SERVICE_USER}
WorkingDirectory=${DRUID_BINARIES}
ExecStart=${DRUID_BINARIES}/bin/start-micro-quickstart
Environment=DRUID_LOG_DIR=${DRUID_LOGS_SL}
Restart=on-failure
RestartSec=10
LimitNOFILE=65536

[Install]
WantedBy=multi-user.target
EOF

    log "INFO" "Reloading systemd daemon"
    systemctl daemon-reload

    log "INFO" "Enabling druid service for boot persistence"
    systemctl enable druid.service >> "$ACCESS_LOG" 2>> "$ERROR_LOG"
}

#----------------------------------------------------------------
# 10. FIREWALL (best-effort, non-fatal)
#----------------------------------------------------------------
open_firewall_ports() {
    local ports=(8081 8082 8083 8088 8090 8091 8888)
    if command -v ufw >/dev/null 2>&1 && ufw status | grep -q "Status: active"; then
        for p in "${ports[@]}"; do ufw allow "${p}/tcp" >> "$ACCESS_LOG" 2>> "$ERROR_LOG" || true; done
        log "INFO" "Opened Druid ports via ufw"
    elif command -v firewall-cmd >/dev/null 2>&1 && systemctl is-active --quiet firewalld; then
        for p in "${ports[@]}"; do firewall-cmd --permanent --add-port="${p}/tcp" >> "$ACCESS_LOG" 2>> "$ERROR_LOG" || true; done
        firewall-cmd --reload >> "$ACCESS_LOG" 2>> "$ERROR_LOG" || true
        log "INFO" "Opened Druid ports via firewalld"
    else
        log "INFO" "No active firewall manager detected, skipping firewall step"
    fi
}

#----------------------------------------------------------------
# 11. START & VERIFY
#----------------------------------------------------------------
start_and_verify() {
    if systemctl is-active --quiet druid.service \
        && curl -s -o /dev/null -w "%{http_code}" "http://localhost:8888/status/health" 2>/dev/null | grep -q "200"; then
        log "INFO" "druid.service is already active and healthy - no restart needed"
    else
        log "INFO" "Starting druid service"
        systemctl restart druid.service

        log "INFO" "Waiting for Druid router (port 8888) to become healthy..."
        local retries=30
        local ok=0
        for ((i=1; i<=retries; i++)); do
            if curl -s -o /dev/null -w "%{http_code}" "http://localhost:8888/status/health" 2>/dev/null | grep -q "200"; then
                ok=1
                break
            fi
            sleep 10
        done

        if [ "$ok" -eq 1 ]; then
            log "INFO" "Druid is UP. Console: http://$(hostname -I | awk '{print $1}'):8888"
        else
            log "ERROR" "Druid did not become healthy in time. Check: journalctl -u druid -f"
            systemctl status druid.service --no-pager >> "$ERROR_LOG" 2>&1 || true
            exit 1
        fi
    fi

    if ! systemctl is-active --quiet druid.service; then
        log "ERROR" "druid.service is not active after startup."
        exit 1
    fi
    log "INFO" "druid.service is active and enabled: $(systemctl is-enabled druid.service)"
}

